// Adds the starting diplomacy to a scenario: economic blocs (customs unions) and bilateral
// treaties in force at the scenario date. Defence blocs (NATO, CSTO) come from
// tools/build_scenarios.py. Rivalries are left to the AI, which names its own from threats,
// opinions and lost land.
//
// Usage: node tools/build_diplomacy.mjs [scenario=modern_2026]
import fs from 'node:fs';

const ROOT = new URL('../', import.meta.url);
const scenId = process.argv[2] || 'modern_2026';
const scenPath = new URL(`data/scenarios/${scenId}.json`, ROOT);
const scenario = JSON.parse(fs.readFileSync(scenPath));
const tags = new Set(scenario.countries.map((c) => c.tag));

// Real-world arrangements, simplified to the game's treaty types (approximate, c. 2026).
const BLOCS = [
  { name: 'European Union', kind: 'economic', members: 'AUT BEL BGR HRV CYP CZE DNK EST FIN FRA DEU GRC HUN IRL ITA LVA LTU LUX MLT NLD POL PRT ROU SVK SVN ESP SWE' },
  { name: 'Mercosur', kind: 'economic', members: 'ARG BRA PRY URY BOL' },
  { name: 'Eurasian Economic Union', kind: 'economic', members: 'RUS BLR KAZ KGZ ARM' },
  { name: 'Gulf Cooperation Council', kind: 'economic', members: 'SAU ARE KWT QAT BHR OMN' },
];
const TREATIES = [
  // mutual defence treaties
  ['alliance', 'USA', 'JPN'], ['alliance', 'USA', 'KOR'], ['alliance', 'USA', 'PHL'], ['alliance', 'USA', 'AUS'],
  ['alliance', 'AUS', 'NZL'], ['alliance', 'CHN', 'PRK'], ['alliance', 'RUS', 'PRK'],
  ['defensive', 'SAU', 'PAK'],
  // free-trade agreements (USMCA, CER)
  ['trade', 'USA', 'CAN'], ['trade', 'USA', 'MEX'], ['trade', 'CAN', 'MEX'], ['trade', 'AUS', 'NZL'],
];

const missing = [];
const blocs = BLOCS.map((b) => {
  const members = b.members.split(' ').filter((t) => tags.has(t) || (missing.push(t), false));
  return { name: b.name, kind: b.kind, members };
});
const treaties = TREATIES.filter(([, a, b]) => (tags.has(a) && tags.has(b)) || (missing.push(`${a}/${b}`), false)).map(([type, a, b]) => ({ type, a, b }));
scenario.diplomacy = {
  note: 'Generated by tools/build_diplomacy.mjs. Customs unions are economic blocs (tariff-free trade); defence treaties are simplified to alliances and defensive pacts.',
  blocs, treaties, rivals: [],
};
fs.writeFileSync(scenPath, JSON.stringify(scenario));
console.log(`${scenId}: ${blocs.length} economic blocs, ${treaties.length} treaties${missing.length ? `; not in scenario: ${missing.join(', ')}` : ''}`);
